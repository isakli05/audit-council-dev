def real_validator_bytes() -> bytes:
    """Decode + verify the frozen validator bytes (fail-closed on any
    drift) and return them."""
    raw = base64.b64decode(_PAYLOAD, validate=True)
    digest = hashlib.sha256(raw).hexdigest()
    assert digest == REAL_VALIDATOR_SHA256, \
        f"REAL_VALIDATOR_BYTES_DRIFT: {digest}"
    assert len(raw) == REAL_VALIDATOR_BYTES_LEN
    return raw


def materialize_real_validator(dst) -> "tuple":
    """Write the byte-exact frozen validator to dst (conftest fixture
    discipline: owner-executable 0755 so make_event_package can rewrite
    the payload bytes in place) and return (path, sha256)."""
    raw = real_validator_bytes()
    dst.parent.mkdir(parents=True, exist_ok=True)
    with open(dst, "wb") as handle:
        handle.write(raw)
    os.chmod(dst, 0o755)
    return dst, REAL_VALIDATOR_SHA256
